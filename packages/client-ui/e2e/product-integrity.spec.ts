import { expect, test } from '@playwright/test';
import { createProductDatabase } from '../test/helpers/product-database.js';
import { onRequestGet as getPosts, onRequestPost as createPost } from '../functions/api/posts.js';
import { onRequestGet as getPost } from '../functions/api/posts/[id].js';
import { onRequestGet as getInteractions, onRequestPost as interact } from '../functions/api/interactions.js';
import { onRequestGet as getCommunities, onRequestPost as community } from '../functions/api/communities.js';
import { onRequestGet as getComments, onRequestPost as comment } from '../functions/api/comments.js';
import { onRequestGet as getNotifications, onRequestPatch as markRead } from '../functions/api/notifications.js';
import { onRequestPost as report } from '../functions/api/report.js';
import { resetReplayNonceCache } from '../functions/api/_auth.js';
import { onRequestGet as getProfiles, onRequestPost as saveProfile } from '../functions/api/profiles.js';
import { onRequestGet as getFollows, onRequestPost as follow } from '../functions/api/follows.js';

test.use({ serviceWorkers: 'block' });

test('social actions persist, failures reconcile, and controls fit every viewport', async ({ page }, testInfo) => {
  test.setTimeout(120000);
  const fixture = createProductDatabase(); resetReplayNonceCache();
  const env = { DB: fixture.database, ENVIRONMENT: 'production' };
  fixture.sqlite.prepare('INSERT INTO posts (id, channel_id, author_id, title, content, created_at) VALUES (?, ?, ?, ?, ?, ?)').run('integrity-post', 'c/technology', 'qa-author', 'A place for useful conversations', 'What makes a community worth coming back to? Share a practice that has worked for your group.', Date.now());
  fixture.sqlite.prepare('INSERT INTO communities (id, name, display_name, description, category, channel_id, created_at) VALUES (?, ?, ?, ?, ?, ?, ?)').run('c-technology', 'technology', 'Technology & Computing', 'Tools, projects and the people building them.', 'Technology', 'c/technology', Date.now());
  const pageErrors: string[] = [];
  page.on('pageerror', error => pageErrors.push(error.stack || error.message));
  let rejectInteractions = false;
  let rejectPublication = false;
  let rejectReports = true;
  await page.addInitScript(() => {
    localStorage.setItem('aetheris_onboarding_completed', 'true');
    localStorage.setItem('aetheris_onboarding_completed_v4', 'true');
    localStorage.setItem('aetheris_proactive_ai_enabled', 'false');
    sessionStorage.setItem('aetheris_push_banner_dismissed', '1');
  });
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url());
    const method = route.request().method();
    const request = new Request(url, { method, headers: route.request().headers(), ...(route.request().postData() ? { body: route.request().postData()! } : {}) });
    let response = Response.json({ success: false, error: 'Unavailable in this isolated test' }, { status: 503 });
    if (url.pathname === '/api/posts') response = method === 'GET' ? await getPosts({ request, env }) : rejectPublication ? Response.json({ success: false, error: 'Publication interrupted; draft kept' }, { status: 503 }) : await createPost({ request, env });
    else if (url.pathname.startsWith('/api/posts/')) response = await getPost({ request, env, params: { id: url.pathname.split('/').at(-1)! } });
    else if (url.pathname === '/api/interactions') response = method === 'GET' ? await getInteractions({ request, env }) : rejectInteractions ? Response.json({ success: false, error: 'Action interrupted; try again' }, { status: 503 }) : await interact({ request, env });
    else if (url.pathname === '/api/communities') response = method === 'GET' ? await getCommunities({ request, env }) : await community({ request, env });
    else if (url.pathname === '/api/comments') response = method === 'GET' ? await getComments({ request, env }) : await comment({ request, env });
    else if (url.pathname === '/api/notifications') response = method === 'GET' ? await getNotifications({ request, env }) : await markRead({ request, env });
    else if (url.pathname === '/api/report') response = rejectReports ? Response.json({ success: false, error: 'Reporting connection interrupted' }, { status: 503 }) : await report({ request, env });
    else if (url.pathname === '/api/profiles') response = method === 'GET' ? await getProfiles({ request, env }) : await saveProfile({ request, env });
    else if (url.pathname === '/api/follows') response = method === 'GET' ? await getFollows({ request, env }) : await follow({ request, env });
    await route.fulfill({ status: response.status, body: await response.text(), contentType: 'application/json' });
  });
  try {
    await page.setViewportSize({ width: 1440, height: 960 });
    await page.goto('/');
    const post = page.locator('[data-post-card-id="integrity-post"]');
    await expect(post).toBeVisible();
    await post.getByRole('button', { name: 'Give Merit' }).click();
    await expect(post.getByRole('button', { name: 'Remove Merit' })).toBeEnabled();
    expect(fixture.sqlite.prepare("SELECT COUNT(*) AS n FROM interactions WHERE interaction_type = 'like'").get()?.n).toBe(1);
    await post.getByRole('button', { name: 'Repost', exact: true }).click();
    await post.locator('[data-pulse-action="do-repost"]').click();
    await expect.poll(() => fixture.sqlite.prepare("SELECT boost_count FROM posts WHERE id = 'integrity-post'").get()?.boost_count).toBe(1);
    await page.reload();
    await expect(post.locator('.btn-pulse-repost-menu')).toHaveClass(/is-active/);
    await post.getByRole('button', { name: 'Repost', exact: true }).click();
    await post.getByRole('button', { name: 'Undo repost', exact: true }).click();
    await expect.poll(() => fixture.sqlite.prepare("SELECT boost_count FROM posts WHERE id = 'integrity-post'").get()?.boost_count).toBe(0);
    rejectInteractions = true;
    await post.getByRole('button', { name: 'Bookmark', exact: true }).click();
    await expect(post.getByRole('button', { name: 'Bookmark', exact: true })).toBeEnabled();
    expect(fixture.sqlite.prepare("SELECT COUNT(*) AS n FROM interactions WHERE interaction_type = 'bookmark'").get()?.n).toBe(0);
    rejectInteractions = false;
    await post.getByRole('button', { name: 'Add reaction' }).click();
    await page.locator('#reactions-portal-overlay').getByRole('button', { name: 'Insight', exact: true }).click();
    await expect(post.getByRole('button', { name: 'Insight: 1' })).toBeVisible();
    await page.reload();
    await expect(post.getByRole('button', { name: 'Insight: 1' })).toBeVisible();

    await post.getByRole('button', { name: 'More options' }).click();
    await page.locator('.post-more-menu [data-action="report-post"]').click();
    await page.locator('#select-dsa-reason').selectOption('spam_scam');
    await page.locator('#textarea-dsa-details').fill('Repeated unwanted promotional content. This is an isolated QA report.');
    await page.locator('#btn-submit-dsa-report').click();
    await expect(page.locator('[data-report-error]')).toContainText('Report not submitted');
    expect(fixture.sqlite.prepare('SELECT COUNT(*) AS n FROM dsa_reports').get()?.n).toBe(0);
    rejectReports = false;
    await page.locator('#btn-submit-dsa-report').click();
    await expect(page.locator('#btn-dsa-done')).toBeVisible();
    expect(fixture.sqlite.prepare('SELECT target_id FROM dsa_reports').get()?.target_id).toBe('integrity-post');
    await page.locator('#btn-dsa-done').click();

    rejectPublication = true;
    await page.getByRole('textbox', { name: 'Post text' }).fill('A draft that must survive a failed publication.');
    await page.locator('#btn-inline-broadcast').click();
    await expect(page.getByRole('button', { name: 'Retry publication' })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('button', { name: 'Retry publication' })).toBeVisible();
    rejectPublication = false;
    await page.getByRole('button', { name: 'Retry publication' }).click();
    await expect.poll(() => fixture.sqlite.prepare('SELECT COUNT(*) AS n FROM posts').get()?.n).toBe(2);
    await expect(page.getByRole('button', { name: 'Retry publication' })).toHaveCount(0);

    for (const width of [360, 390, 768, 1024, 1440, 1920]) {
      await page.setViewportSize({ width, height: 900 });
      await post.getByRole('button', { name: 'Add reaction' }).click();
      const portal = page.locator('#reactions-portal-overlay');
      await expect(portal).toBeVisible();
      const box = (await portal.boundingBox())!;
      expect(box.x).toBeGreaterThanOrEqual(0);
      expect(box.x + box.width).toBeLessThanOrEqual(width);
      expect(box.y + box.height).toBeLessThanOrEqual(900);
      await page.keyboard.press('Escape');
      await expect(portal).toHaveCount(0);
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
      expect(overflow).toBe(false);
      await page.screenshot({ path: testInfo.outputPath(`home-${width}.png`) });
    }
    await post.locator('.social-post__author').click();
    await page.locator('#btn-toggle-follow').click();
    await expect(page.locator('#btn-toggle-follow')).toBeEnabled();
    expect(fixture.sqlite.prepare('SELECT COUNT(*) AS n FROM follows').get()?.n).toBe(1);
    await page.locator('#btn-toggle-follow').click();
    await expect(page.locator('#btn-toggle-follow')).toBeEnabled();
    expect(fixture.sqlite.prepare('SELECT COUNT(*) AS n FROM follows').get()?.n).toBe(0);
    await page.locator('[data-testid="nav-item-profile"]').click();
    await page.getByRole('button', { name: 'Edit profile', exact: true }).click();
    await page.locator('#edit-profile-name').fill('Test participant');
    await page.locator('#edit-profile-handle').fill('test_participant');
    await page.locator('#edit-profile-bio').fill('A profile stored through the signed API.');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(page.locator('#edit-profile-modal-overlay')).toHaveCount(0);
    expect(fixture.sqlite.prepare('SELECT display_name FROM user_profiles').get()?.display_name).toBe('Test participant');
    await page.reload();
    await expect(page.locator('#sovereign-profile-container')).toContainText('Test participant');
    const owner = await page.evaluate(() => (window as any).clientStore.keypair.fingerprint);
    fixture.sqlite.prepare('INSERT INTO notifications (id, user_id, actor_id, type, preview_text, created_at) VALUES (?, ?, ?, ?, ?, ?)').run('qa-notification', owner, 'qa-author', 'reply_post', 'A reply for the local QA participant', Date.now());
    await page.locator('#btn-toggle-notifs').click();
    await expect(page.locator('#notification-panel')).toContainText('A reply for the local QA participant');
    await page.locator('[data-action="notif-mark-all-read"]').click();
    await expect.poll(() => fixture.sqlite.prepare("SELECT is_read FROM notifications WHERE id = 'qa-notification'").get()?.is_read).toBe(1);
    await page.reload();
    await page.locator('#btn-toggle-notifs').click();
    await expect(page.locator('#notification-panel')).toContainText('A reply for the local QA participant');
    expect(fixture.sqlite.prepare("SELECT is_read FROM notifications WHERE id = 'qa-notification'").get()?.is_read).toBe(1);
    expect(pageErrors).toEqual([]);
  } finally { fixture.sqlite.close(); }
});
